"""Generates src/ui/fallback_glyphs.inc: the glyphs the Omni Mono does not draw (Chinese and
Japanese ideographs and kana, full-width punctuation, Greek, Cyrillic, extra Latin letters).

Source: Fusion Pixel Font, 10px proportional, Simplified Chinese build (OFL-1.1, TakWolf),
third_party/fusion-pixel-font/. Its 10 px grid has the Omni's metrics: Latin capitals are 7 px
tall on the same baseline, so the glyphs sit on the Omni's 12-row line box unchanged (an
ideograph takes rows 1..9, a capital rows 2..8). The outlines are whole pixels, so FreeType's
monochrome raster reproduces them exactly; nothing is resampled.

The Omni keeps every character it already has: only codepoints missing from src/ui/assets.inc
are taken. Hangul is left out (not one of Cue's interface languages; it would double the table).

Run: python3 tools/gen_fallback_glyphs.py   (needs freetype-py and fontTools on the dev machine)
"""
import os, re, sys
import freetype
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = os.path.join(ROOT, "third_party/fusion-pixel-font/fusion-pixel-10px-proportional-zh_hans.woff")
OUT = os.path.join(ROOT, "src/ui/fallback_glyphs.inc")
BASELINE = 9   # first row below the Omni baseline
ROWS = 12
RANGES = [
    (0x00A1, 0x024F),  # Latin-1 supplement, Latin extended A/B
    (0x0370, 0x03FF),  # Greek
    (0x0400, 0x04FF),  # Cyrillic
    (0x2010, 0x206F),  # general punctuation
    (0x20A0, 0x20CF),  # currency
    (0x2190, 0x21FF),  # arrows
    (0x3000, 0x303F),  # CJK punctuation
    (0x3040, 0x30FF),  # kana
    (0x3400, 0x4DBF),  # CJK extension A
    (0x4E00, 0x9FFF),  # CJK unified ideographs
    (0xFF00, 0xFFEF),  # full-width forms
]


def c_literal(seq):
    """Decodes a run of adjacent C string literals into text."""
    out = bytearray()
    for part in re.findall(r'"((?:[^"\\]|\\.)*)"', seq):
        i = 0
        while i < len(part):
            if part[i] == "\\" and part[i + 1] == "x":
                out.append(int(part[i + 2:i + 4], 16)); i += 4
            elif part[i] == "\\":
                out.append(ord(part[i + 1])); i += 2
            else:
                out.append(ord(part[i])); i += 1
    return out.decode("utf-8")


def omni_codepoints():
    src = open(os.path.join(ROOT, "src/ui/assets.inc"), encoding="utf-8").read()
    body = src[src.index("kGlyphs[]"):src.index("kBitmaps[]")]
    cps = set()
    for m in re.finditer(r'^  \{(.*?), \d+, "[.#]+"\},$', body, re.M):
        cps.add(ord(c_literal(m.group(1))[0]))
    return cps


def main():
    have = omni_codepoints()
    cmap = TTFont(FONT).getBestCmap()
    face = freetype.Face(FONT)
    face.set_pixel_sizes(0, 10)
    cps = sorted(c for c in cmap for a, b in RANGES if a <= c <= b and c not in have)
    records, clipped = [], 0
    for cp in cps:
        face.load_char(chr(cp), freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_MONO | freetype.FT_LOAD_NO_HINTING)
        g = face.glyph
        bm = g.bitmap
        adv = int(round(g.advance.x / 64))
        if adv <= 0 or adv > 16:
            continue
        rows = [0] * ROWS
        for r in range(bm.rows):
            y = BASELINE - g.bitmap_top + r
            for x in range(bm.width):
                if not bm.buffer[r * bm.pitch + x // 8] & (0x80 >> (x % 8)):
                    continue
                gx = g.bitmap_left + x
                if 0 <= y < ROWS and 0 <= gx < 16:
                    rows[y] |= 1 << gx
                else:
                    clipped += 1
        records.append((cp, adv, rows))
    lines = [
        "// Generated by tools/gen_fallback_glyphs.py. Do not edit by hand.",
        "// Glyphs the Omni Mono does not have, from Fusion Pixel Font 10px (zh_hans), OFL-1.1,",
        "// Copyright (c) 2022, TakWolf, Reserved Font Name 'Fusion Pixel'. This table is a converted",
        "// subset (not a font named Fusion Pixel); license in third_party/fusion-pixel-font/OFL.txt.",
        "// Each record: codepoint | advance << 24, then 12 rows of 16 bits (bit x = column x).",
        f"static constexpr int kFallbackCount = {len(records)};",
        "static const uint32_t kFallbackCp[kFallbackCount] = {",
    ]
    for i in range(0, len(records), 12):
        lines.append("  " + ", ".join("0x%08x" % (cp | adv << 24) for cp, adv, _ in records[i:i + 12]) + ",")
    lines.append("};")
    lines.append("static const uint16_t kFallbackRows[kFallbackCount][12] = {")
    for cp, adv, rows in records:
        lines.append("  {" + ",".join(str(r) for r in rows) + "},")
    lines.append("};")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}: {len(records)} glyphs ({clipped} pixels outside the 12-row box clipped)")


if __name__ == "__main__":
    main()
