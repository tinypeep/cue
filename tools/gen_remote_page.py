"""Embeds the phone remote's page (assets/remote/index.html) into the program.

  python3 tools/gen_remote_page.py           writes src/win/remote_page.inc
  python3 tools/gen_remote_page.py --check   fails when the .inc is out of date

The page is split in raw string pieces under MSVC's 16 KB literal limit; the server joins them
once. Comments-only lines and leading indentation are dropped to keep the binary small.
"""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "remote", "index.html")
OUT = os.path.join(ROOT, "src", "win", "remote_page.inc")
DELIM = "CUEPAGE"
PIECE = 12000


def build():
    lines = []
    for line in open(SRC, encoding="utf-8").read().splitlines():
        s = line.strip()
        if s.startswith("// ") or s == "//":
            continue
        lines.append(s)
    text = "\n".join(lines) + "\n"
    if ")" + DELIM + '"' in text:
        raise SystemExit("the page contains the raw string delimiter")
    pieces, cur = [], ""
    for line in text.splitlines(keepends=True):
        if len((cur + line).encode("utf-8")) > PIECE:
            pieces.append(cur)
            cur = ""
        cur += line
    if cur:
        pieces.append(cur)
    out = ["// Generated by tools/gen_remote_page.py from assets/remote/index.html. Do not edit by hand.",
           "static const char* const kRemotePage[] = {"]
    for p in pieces:
        out.append('R"' + DELIM + "(" + p + ")" + DELIM + '",')
    out.append("};")
    return "\n".join(out) + "\n"


def main():
    data = build()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != data:
            print("src/win/remote_page.inc is out of date: run python3 tools/gen_remote_page.py")
            sys.exit(1)
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(data)
    print("wrote", os.path.relpath(OUT, ROOT), len(data), "bytes")


if __name__ == "__main__":
    main()
