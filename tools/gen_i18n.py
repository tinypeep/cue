"""Generates the compiled translation catalog from i18n/*.json.

  python3 tools/gen_i18n.py            writes src/core/strings.h and src/core/i18n_catalog.inc
  python3 tools/gen_i18n.py --check    only validates (non-zero exit on any problem)

Rules checked here (and again at run time by tests/i18n_test.cpp):
  * English is the fallback, so it must define every key.
  * Every other catalog must define every key too (a missing key falls back to English at run
    time, but a release must not ship with gaps).
  * Every translation uses exactly the placeholders of the English text ({version}, {n}...).
  * Plural keys are objects {"one": ..., "other": ...}; "other" is always required, "one" is
    required where the language has a singular form.
  * No key exists in a translation that English does not have (a typo would be silently unused).
Keys are stable: code refers to them as str::<key with dots replaced by underscores>.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANGS = ["pt-BR", "en", "es", "fr", "zh-Hans"]   # same order as i18n::Lang
HAS_ONE = {"pt-BR": True, "en": True, "es": True, "fr": True, "zh-Hans": False}
PH = re.compile(r"\{([a-z_]+)\}")


def load(tag):
    with open(os.path.join(ROOT, "i18n", tag + ".json"), encoding="utf-8") as f:
        data = json.load(f)
    return {k: v for k, v in data.items() if not k.startswith("_")}


def forms(v):
    return v if isinstance(v, dict) else {"other": v}


def main():
    check_only = "--check" in sys.argv
    cats = {t: load(t) for t in LANGS}
    en = cats["en"]
    keys = list(en.keys())
    problems = []
    for tag in LANGS:
        cat = cats[tag]
        for k in cat:
            if k not in en:
                problems.append(f"{tag}: unknown key {k}")
        for k in keys:
            if k not in cat:
                problems.append(f"{tag}: missing {k}")
                continue
            ref, val = forms(en[k]), forms(cat[k])
            if isinstance(en[k], dict) != isinstance(cat[k], dict):
                problems.append(f"{tag}: {k} plural shape differs from English")
                continue
            want = set(PH.findall(ref["other"]))
            if isinstance(en[k], dict):
                if "other" not in val:
                    problems.append(f"{tag}: {k} needs an 'other' form")
                if HAS_ONE[tag] and "one" not in val:
                    problems.append(f"{tag}: {k} needs a 'one' form")
            for name, text in val.items():
                if not isinstance(text, str) or not text:
                    problems.append(f"{tag}: {k}.{name} is empty")
                    continue
                got = set(PH.findall(text))
                if got != want:
                    problems.append(f"{tag}: {k}.{name} placeholders {sorted(got)} != {sorted(want)}")
                if text != text.strip():
                    problems.append(f"{tag}: {k}.{name} has leading/trailing spaces")
    for p in problems:
        print("i18n:", p)
    if problems:
        sys.exit(1)
    if check_only:
        print(f"i18n ok: {len(keys)} keys x {len(LANGS)} languages")
        return

    def ident(k):
        return k.replace(".", "_")

    def cstr(s):
        if s is None:
            return "nullptr"
        out = []
        for b in s.encode("utf-8"):
            c = chr(b)
            if c in '"\\':
                out.append("\\" + c)
            elif c == "\n":
                out.append("\\n")
            elif 32 <= b < 127:
                out.append(c)
            else:
                out.append("\\x%02x\"\"" % b)
        return '"' + "".join(out) + '"'

    h = ["// Generated by tools/gen_i18n.py from i18n/*.json. Do not edit by hand.",
         "// Stable keys: \"home.open_file\" in the catalogs is str::home_open_file here.",
         "#pragma once", "#include <cstdint>", "", "namespace str {", "enum Id : uint16_t {"]
    for k in keys:
        h.append(f"  {ident(k)},")
    h += ["  kCount", "};", "}  // namespace str", ""]
    with open(os.path.join(ROOT, "src/core/strings.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(h))

    c = ["// Generated by tools/gen_i18n.py from i18n/*.json. Do not edit by hand.",
         "// Included only by src/core/i18n.cpp. nullptr = not translated (English is used).", ""]
    c.append("static const char* const kKeyNames[str::kCount] = {")
    for k in keys:
        c.append(f"  {cstr(k)},")
    c.append("};")
    c.append("static const bool kPluralKey[str::kCount] = {")
    c.append("  " + ", ".join("true" if isinstance(en[k], dict) else "false" for k in keys))
    c.append("};")
    for table, form in (("kOther", "other"), ("kOne", "one")):
        c.append(f"static const char* const {table}[{len(LANGS)}][str::kCount] = {{")
        for tag in LANGS:
            c.append(f"  {{  // {tag}")
            for k in keys:
                v = cats[tag].get(k)
                text = None
                if v is not None:
                    fv = forms(v)
                    text = fv.get(form) if (form == "other" or isinstance(v, dict)) else None
                c.append(f"    {cstr(text)},")
            c.append("  },")
        c.append("};")
    with open(os.path.join(ROOT, "src/core/i18n_catalog.inc"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(c) + "\n")
    print(f"wrote strings.h and i18n_catalog.inc: {len(keys)} keys x {len(LANGS)} languages")


if __name__ == "__main__":
    main()
