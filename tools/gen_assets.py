"""Generates src/ui/assets.inc and the PNG preview of the supplied app icon.

Sources:
  * Omni design system bundle (glyphs, icons, sprites copied 1:1 from Omni)
  * Cue icons below, drawn in the same grammar (1 block, 5..9 px of art)
  * "Clean" / "Readable" labels rasterized from the shipped subtitle fonts
Run: python3 tools/gen_assets.py <omni-data.json> <player-root>
"""
import json, sys, os
from PIL import Image, ImageDraw, ImageFont

data = json.load(open(sys.argv[1]))
root = sys.argv[2]

# Cue icons. Same rules as Omni: monochrome, one ink, '#' = 1 px of art.
PLAYER_ICONS = {
    "rewind": ["...#...#", "..##..##", ".###.###", "..##..##", "...#...#"],
    "forward": ["#...#...", "##..##..", "###.###.", "##..##..", "#...#..."],
    "cc": ["#########", "#.......#", "#.##.##.#", "#.#..#..#", "#.##.##.#", "#.......#", "#########"],
    "fs-enter": ["###.###", "#.....#", "#.....#", ".......", "#.....#", "#.....#", "###.###"],
    "fs-exit": [".#...#.", ".#...#.", "##...##", ".......", "##...##", ".#...#.", ".#...#."],
    "chev-left": ["..#", ".#.", "#..", ".#.", "..#"],
    "chev-right5": ["#..", ".#.", "..#", ".#.", "#.."],
    "minus": [".....", ".....", "#####", ".....", "....."],
    "plus": ["..#..", "..#..", "#####", "..#..", "..#.."],
    "resume": [".#....", "######", ".#...#", ".....#", "..####"],
    "grip": ["#.#", "...", "#.#", "...", "#.#"],
    "win-max": ["#####", "#...#", "#...#", "#...#", "#####"],
    "win-restore": ["..####", "..#..#", "####.#", "#..###", "#..#..", "####.."],
    "win-min": ["#####"],
    # repeat the file: two arrows chasing each other around a rectangle
    "loop": ["......#..", ".#######.", "#.....#..", "#.......#", "..#.....#", ".#######.", "..#......"],
    "play": ["#......", "###....", "#####..", "#######", "#####..", "###....", "#......"],
    "pause": ["##...##", "##...##", "##...##", "##...##", "##...##", "##...##", "##...##"],
}

icons = dict(data["icons"])
for k, v in PLAYER_ICONS.items():
    assert k not in icons, k
    w = len(v[0]); assert all(len(r) == w for r in v), k
    icons[k] = v
sprites = data["sprites"]
glyphs = data["glyphs"]

def cstr(s):
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c in '"\\': out.append("\\" + c)
        elif 32 <= b < 127: out.append(c)
        else: out.append("\\x%02x\"\"" % b)
    return '"' + "".join(out) + '"'

lines = ["// Generated by tools/gen_assets.py. Do not edit by hand.",
         "// Glyphs, icons and sprites come from the Omni design system (1:1).", ""]

lines.append("static const GlyphDef kGlyphs[] = {")
for ch, (w, rows) in glyphs.items():
    r = rows.split("|"); assert len(r) == 12, ch
    lines.append("  {%s, %d, %s}," % (cstr(ch), w, cstr("".join(r))))
lines.append("};")
lines.append("")
lines.append("static const BitmapDef kBitmaps[] = {")
for name, rows in list(icons.items()) + [("sprite:" + k, v) for k, v in sprites.items()]:
    w = len(rows[0]); h = len(rows)
    lines.append("  {%s, %d, %d, %s}," % (cstr(name), w, h, cstr("".join(rows))))
lines.append("};")
lines.append("")

# Font labels for the subtitle font picker: each option is drawn in its own font.
fonts = {"Clean": os.path.join(root, "assets/fonts/CueClean.ttf"),
         "Readable": os.path.join(root, "assets/fonts/CueReadable.ttf")}
lines.append("static const MaskDef kMasks[] = {")
for label, path in fonts.items():
    for s in range(1, 9):
        cap = 7 * s                      # cap height matches Omni Mono (7 px of art)
        size = 10
        while True:
            f = ImageFont.truetype(path, size)
            bb = f.getbbox("H")
            if bb[3] - bb[1] >= cap or size > 400: break
            size += 1
        f = ImageFont.truetype(path, size)
        asc = f.getbbox("H")[1]
        w = int(f.getlength(label)) + 2
        h = 12 * s                        # same line box as Omni Mono
        img = Image.new("L", (w, h), 0)
        d = ImageDraw.Draw(img)
        # baseline of Omni Mono sits after row 9 (cap rows 2..8)
        d.text((0, 2 * s - asc), label, font=f, fill=255)
        bbox = img.getbbox()
        if bbox: img = img.crop((0, 0, bbox[2] + 1, h)); w = img.width
        hexs = "".join("\\x%02x" % p for p in img.getdata())
        lines.append('  {"%s", %d, %d, %d, "%s"},' % (label, s, w, h, hexs))
lines.append("};")

out = os.path.join(root, "src/ui/assets.inc")
open(out, "w").write("\n".join(lines) + "\n")
print("wrote", out, len(glyphs), "glyphs", len(icons), "icons", len(sprites), "sprites")

# res/cue.ico is the canonical, user-supplied icon. Keep its authored sizes intact.
# Regenerating the UI assets must not replace it with an older generated design.
icon_path = os.path.join(root, "res/cue.ico")
app_icon = Image.open(icon_path)
app_icon.ico.getimage((256, 256)).save(os.path.join(root, "res/cue-256.png"))
print("refreshed res/cue-256.png from res/cue.ico")
