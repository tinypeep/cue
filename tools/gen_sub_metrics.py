"""Generates src/core/sub_metrics.inc: advance widths of the three subtitle fonts, so the
player can know exactly where the engine (libass) draws each subtitle line.
libass sizes a font so that OS/2 usWinAscent + usWinDescent equals the font size.
Run: python3 tools/gen_sub_metrics.py <player-root>"""
import sys, os
from fontTools.ttLib import TTFont
root = sys.argv[1]
fonts = ["CueOmni", "CueClean", "CueReadable"]
ranges = [(0x20, 0x7E), (0xA0, 0x24F), (0x2000, 0x206F), (0x20AC, 0x20AC), (0x2122, 0x2122), (0x266A, 0x266B)]
out = ["// Generated by tools/gen_sub_metrics.py. Do not edit by hand.", ""]
for i, f in enumerate(fonts):
    t = TTFont(os.path.join(root, "assets/fonts", f + ".ttf"))
    upm = t["head"].unitsPerEm
    os2 = t["OS/2"]
    cmap = t.getBestCmap()
    hmtx = t["hmtx"]
    fallback = hmtx[cmap[ord("n")]][0]
    rows = []
    for a, b in ranges:
        for cp in range(a, b + 1):
            g = cmap.get(cp)
            if g is not None:
                rows.append((cp, hmtx[g][0]))
    out.append("static const SubGlyph kSubGlyphs%d[] = {" % i)
    line = "  "
    for cp, adv in rows:
        line += "{0x%04X,%d}," % (cp, adv)
        if len(line) > 100:
            out.append(line); line = "  "
    if line.strip(): out.append(line)
    out.append("};")
    out.append("static const SubFontMetrics kSubFont%d = {%d, %d, %d, %d, kSubGlyphs%d, %d};" %
               (i, upm, os2.usWinAscent, os2.usWinDescent, fallback, i, len(rows)))
    out.append("")
open(os.path.join(root, "src/core/sub_metrics.inc"), "w").write("\n".join(out) + "\n")
print("wrote sub_metrics.inc")
